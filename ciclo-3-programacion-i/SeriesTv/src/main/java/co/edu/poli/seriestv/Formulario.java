    private void guardarSerie() {
    try {
        // Validar campos obligatorios
        if (txtCodigo.getText().isEmpty() || txtTituloSerie.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Código y Título son obligatorios", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Preparar la consulta SQL
        String sql = "INSERT INTO serie (codigo, titulo, fecha, temporadas, genero, actores, sinopsis) VALUES (?, ?, ?, ?, ?, ?, ?)";
        PreparedStatement statement = connection.prepareStatement(sql);
        statement.setString(1, txtCodigo.getText());
        statement.setString(2, txtTituloSerie.getText());
        statement.setString(3, txtFechaLanzamiento.getText());
        statement.setString(4, txtTemporadas.getText());
        statement.setString(5, cboGenero.getSelectedItem().toString());
        statement.setString(6, txtActores.getText());
        statement.setString(7, txtSinopsis.getText());
        
        // Ejecutar la consulta
        int filasInsertadas = statement.executeUpdate();
        if (filasInsertadas > 0) {
            JOptionPane.showMessageDialog(this, "Serie guardada exitosamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            limpiarCampos();
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
}

private void buscarSerie() {
    try {
        if (txtCodigo.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese un código para buscar", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        String sql = "SELECT * FROM serie WHERE codigo = ?";
        PreparedStatement statement = connection.prepareStatement(sql);
        statement.setString(1, txtCodigo.getText());
        
        ResultSet resultSet = statement.executeQuery();
        
        if (resultSet.next()) {
            // Llenar los campos con los datos encontrados
            txtTituloSerie.setText(resultSet.getString("titulo"));
            txtFechaLanzamiento.setText(resultSet.getString("fecha"));
            txtTemporadas.setText(resultSet.getString("temporadas"));
            txtActores.setText(resultSet.getString("actores"));
            txtSinopsis.setText(resultSet.getString("sinopsis"));
            
            // Seleccionar el género
            String genero = resultSet.getString("genero");
            for (int i = 0; i < cboGenero.getItemCount(); i++) {
                if (cboGenero.getItemAt(i).equals(genero)) {
                    cboGenero.setSelectedIndex(i);
                    break;
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró la serie", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al buscar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
}
    
    
